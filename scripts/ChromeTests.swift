import Foundation

@main struct ChromeTests {
    @MainActor static func main() async throws {
        let chrome = ChromeState()
        chrome.scheduleHide()
        try await Task.sleep(nanoseconds: 1_050_000_000)
        precondition(!chrome.visible)
        chrome.reveal(); precondition(chrome.visible)
        chrome.togglePin(); chrome.scheduleHide()
        try await Task.sleep(nanoseconds: 1_050_000_000)
        precondition(chrome.pinned && chrome.visible)
        chrome.togglePin()
        try await Task.sleep(nanoseconds: 1_050_000_000)
        precondition(!chrome.pinned && !chrome.visible)
        chrome.dispose()
        let inspector = InspectorState()
        inspector.pointer(x: 500, width: 1000, enabled: true)
        precondition(!inspector.visible)
        inspector.pointer(x: 990, width: 1000, enabled: true)
        precondition(inspector.visible)
        inspector.pointer(x: 750, width: 1000, enabled: true)
        try await Task.sleep(nanoseconds: 350_000_000)
        precondition(inspector.visible)
        inspector.pointer(x: 500, width: 1000, enabled: true)
        try await Task.sleep(nanoseconds: 350_000_000)
        precondition(!inspector.visible)
        inspector.togglePin()
        inspector.pointer(x: 100, width: 1000, enabled: true)
        precondition(inspector.pinned && inspector.visible)
        inspector.togglePin()
        inspector.pointer(x: 500, width: 1000, enabled: true)
        try await Task.sleep(nanoseconds: 350_000_000)
        precondition(!inspector.visible)
        inspector.pointer(x: 990, width: 1000, enabled: false)
        precondition(!inspector.visible)
        inspector.pointer(x: 990, width: 1000, enabled: true, panelWidth: 372)
        inspector.pointer(x: 640, width: 1000, enabled: true, panelWidth: 372)
        try await Task.sleep(nanoseconds: 350_000_000)
        precondition(inspector.visible)
        inspector.pointer(x: 580, width: 1000, enabled: true, panelWidth: 372)
        try await Task.sleep(nanoseconds: 350_000_000)
        precondition(!inspector.visible)
        inspector.dispose()
        print("PASS inspector edge reveal, panel retention, delayed exit, pinning and unavailable result")
        print("PASS delayed auto-hide, pointer reveal and pin/unpin lifecycle")
    }
}
